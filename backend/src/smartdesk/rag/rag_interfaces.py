from typing import Protocol

from smartdesk.rag.rag_models import Chunk, Embedding, EvidenceVerdict, GroundedAnswer, Passage


class Embedder(Protocol):
    @property
    def signature(self) -> str: ...
    def embed_documents(self, texts: list[str]) -> list[Embedding]: ...
    def embed_query(self, query: str) -> Embedding: ...


class KnowledgeStore(Protocol):
    def ensure_collection(self, dimension: int) -> None: ...
    def records(self) -> dict[str, Chunk]: ...
    def upsert(self, records: list[Chunk], vectors: list[Embedding], signature: str) -> None: ...
    def delete(self, chunk_ids: list[str]) -> None: ...
    def search(
        self, vectors: Embedding, mode: str, limit: int, access_scope: str
    ) -> list[Passage]: ...


class Reranker(Protocol):
    def rank(self, query: str, passages: list[Passage]) -> list[Passage]: ...


class Retriever(Protocol):
    def search(self, query: str, mode: str = "reranked") -> list[Passage]: ...


class AnswerModel(Protocol):
    def answer(self, data: dict) -> GroundedAnswer: ...
    def verify(self, data: dict) -> EvidenceVerdict: ...
